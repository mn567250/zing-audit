def marked_tests(test_dir: Path = HERE) -> dict[str, list[str]]:
    """Static scan of tests/a11y/test_*.py: step -> test functions marked with it."""
    out: dict[str, list[str]] = {}
    for path in sorted(test_dir.glob("test_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        consts: dict[str, list[str]] = {}
        for node in tree.body:
            if isinstance(node, ast.Assign) and isinstance(node.value, (ast.Tuple, ast.List)):
                vals = [e.value for e in node.value.elts if isinstance(e, ast.Constant) and isinstance(e.value, str)]
                for t in node.targets:
                    if isinstance(t, ast.Name):
                        consts[t.id] = vals
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) or not node.name.startswith("test"):
                continue
            for d in node.decorator_list:
                if not (isinstance(d, ast.Call) and isinstance(d.func, ast.Attribute) and d.func.attr == "bitv"):
                    continue
                for a in d.args:
                    vals = (
                        consts.get(a.value.id, []) if isinstance(a, ast.Starred) and isinstance(a.value, ast.Name)
                        else [a.value] if isinstance(a, ast.Constant) and isinstance(a.value, str) else []
                    )
                    for v in vals:
                        lst = out.setdefault(v, [])
                        if node.name not in lst:
                            lst.append(node.name)
    return out


def docs_table(cat: dict[str, Any] | None = None, tests: dict[str, list[str]] | None = None) -> str:
    cat = cat or catalogue()
    tests = marked_tests() if tests is None else tests
    lines = [
        "| Step | WCAG 2.1 | Level | Title | Automation | How | Tests |",
        "|---|---|---|---|---|---|---|",
    ]
    for c in cat["steps"]:
        names = ", ".join(f"`{t}`" for t in tests.get(c["step"], [])) or "—"
        how = c["how"].replace("|", "\\|")
        lines.append(f"| {c['step']} | {c['wcag']} | {c['level']} | {c['title']} | {c['automation']} | {how} | {names} |")
    extra = sorted(set(tests) - {c["step"] for c in cat["steps"]}, key=_step_key)
    for step in extra:
        names = ", ".join(f"`{t}`" for t in tests[step])
        lines.append(f"| {step} | — | — | beyond WCAG (EN 301 549 clause {step}) | auto | — | {names} |")
    return "\n".join(lines)


def update_docs(path: Path = DOCS) -> bool:
    text = path.read_text(encoding="utf-8")
    if DOCS_START not in text or DOCS_END not in text:
        raise SystemExit(f"{path}: coverage table markers not found")
    head, rest = text.split(DOCS_START, 1)
    _, tail = rest.split(DOCS_END, 1)
    new = f"{head}{DOCS_START}\n{docs_table()}\n{DOCS_END}{tail}"
    if new != text:
        path.write_text(new, encoding="utf-8")
        return True
    return False


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m tests.a11y.conformance", description=__doc__.split("\n\n")[0])
    ap.add_argument("--results", type=Path, help="per-step results written by the a11y suite (ZING_A11Y_RESULTS)")
    ap.add_argument("--llm", type=Path, help="optional semi-automated review notes per step")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help=f"report to write (default: {DEFAULT_OUT.relative_to(ROOT)})")
    ap.add_argument("--docs", action="store_true", help="rewrite the coverage table in docs/ACCESSIBILITY.md")
    args = ap.parse_args(argv)
    if not args.results and not args.docs:
        ap.error("give --results and/or --docs")
    if args.docs:
        print(("updated " if update_docs() else "unchanged ") + str(DOCS.relative_to(ROOT)))
    if args.results:
        results = json.loads(args.results.read_text(encoding="utf-8")) if args.results.exists() else None
        if results is None:
            print(f"warning: {args.results} not found, every step is reported as not tested", file=sys.stderr)
        llm = None
        if args.llm:
            if args.llm.exists():
                llm = json.loads(args.llm.read_text(encoding="utf-8"))
            else:
                print(f"warning: {args.llm} not found, no review notes merged", file=sys.stderr)
        report = build_report(results, llm, commit=_git_commit())
        args.out.write_text(json.dumps(report, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        t = report["totals"]
        print(
            f"wrote {args.out}: {t['status']['pass']['count']} pass, {t['status']['fail']['count']} fail, "
            f"{t['status']['not tested']['count']} not tested, "
            f"{t['status']['manual review pending']['count']} manual review pending, {t['status']['n/a']['count']} n/a"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
